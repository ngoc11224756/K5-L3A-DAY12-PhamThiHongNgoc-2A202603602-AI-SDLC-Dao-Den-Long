import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const CLI = join(ROOT, 'dist', 'headless.mjs');
const PROOF_DIR = join(ROOT, 'docs', 'proof', 'phase-1');

mkdirSync(PROOF_DIR, { recursive: true });

function runCase(name, { seed, ticks, snapshotEvery = 10, scenario, inputs }) {
  const args = [
    CLI,
    '--seed',
    String(seed),
    '--night',
    '1',
    '--ticks',
    String(ticks),
    '--snapshot-every',
    String(snapshotEvery)
  ];

  if (scenario) {
    const scPath = join(PROOF_DIR, `${name}.scenario.json`);
    writeFileSync(scPath, JSON.stringify(scenario, null, 2) + '\n', 'utf8');
    args.push('--scenario', scPath);
  }
  if (inputs) {
    const inPath = join(PROOF_DIR, `${name}.inputs.json`);
    writeFileSync(inPath, JSON.stringify(inputs, null, 2) + '\n', 'utf8');
    args.push('--inputs', inPath);
  }

  const outPath = join(PROOF_DIR, `${name}.out.jsonl`);
  args.push('--out', outPath);

  execFileSync(process.execPath, args, { cwd: ROOT, stdio: 'pipe' });
  const raw = readFileSync(outPath, 'utf8');
  const hash = createHash('sha256').update(raw).digest('hex');
  const lines = raw.trim().split('\n').map((l) => JSON.parse(l));
  return { outPath, hash, lines, end: lines.at(-1) };
}

// 1. Win scenario: pick 4 motes -> deposit -> light L1 (L2..L5 pre-lit) -> won
const winRes = runCase('01-win-all-lit', {
  seed: 100,
  ticks: 240,
  snapshotEvery: 20,
  scenario: {
    random_motes: false,
    random_shades: false,
    player: { pos: [0, 0, 0], carried: 0, flames: 3 },
    motes: [
      [0, 0, 2],
      [0, 0, 4],
      [0, 0, 6],
      [0, 0, 8]
    ],
    shades: [],
    time_left_s: 120,
    lanterns: [
      { id: 'L1', pos: [0, 0, 10], deposited: 0, lit: false },
      { id: 'L2', lit: true },
      { id: 'L3', lit: true },
      { id: 'L4', lit: true },
      { id: 'L5', lit: true }
    ]
  },
  inputs: {
    frames: [
      { tick: 0, move: [0, 1], cam_yaw_deg: 0 },
      { tick: 75, move: [0, 0], interact: true },
      { tick: 76, interact: false }
    ]
  }
});

// 2. Pulse & safe-radius scenario
const pulseRes = runCase('02-pulse-and-safe-zone', {
  seed: 101,
  ticks: 200,
  snapshotEvery: 20,
  scenario: {
    random_motes: false,
    random_shades: false,
    player: { pos: [0, 0, 0], carried: 2, flames: 3 },
    motes: [],
    lanterns: [{ id: 'L1', pos: [0, 0, 0], lit: true }],
    shades: [{ id: 'S1', pos: [7, 0, 0] }]
  },
  inputs: {
    frames: [
      { tick: 0, pulse: true },
      { tick: 1, pulse: false }
    ]
  }
});

// 3. Determinism check (run default night 1 twice with same seed)
const detA = runCase('03-determinism-runA', {
  seed: 42,
  ticks: 300,
  snapshotEvery: 30,
  inputs: {
    frames: [
      { tick: 0, move: [0.5, 0.8], cam_yaw_deg: 30 },
      { tick: 90, move: [-0.7, 0.4], jump: true },
      { tick: 91, jump: false }
    ]
  }
});
const detB = runCase('03-determinism-runB', {
  seed: 42,
  ticks: 300,
  snapshotEvery: 30,
  inputs: {
    frames: [
      { tick: 0, move: [0.5, 0.8], cam_yaw_deg: 30 },
      { tick: 90, move: [-0.7, 0.4], jump: true },
      { tick: 91, jump: false }
    ]
  }
});

if (detA.hash !== detB.hash) {
  console.error('Determinism check FAILED!');
  process.exit(1);
}

