import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const CLI = join(ROOT, 'dist', 'headless.mjs');
const PROOF_DIR = join(ROOT, 'docs', 'proof', 'phase-3');

mkdirSync(PROOF_DIR, { recursive: true });

function runCase(name, { seed, night, ticks, snapshotEvery = 20, scenario, inputs }) {
  const args = [
    CLI,
    '--seed',
    String(seed),
    '--night',
    String(night),
    '--ticks',
    String(ticks),
    '--snapshot-every',
    String(snapshotEvery)
  ];

  if (scenario) {
    const scPath = join(PROOF_DIR, `${name}.scenario.json`);
    writeFileSync(scPath, JSON.stringify(scenario, null, 2) + '\n', 'utf8');
    args.push('--scenario', scPath);
  }
  if (inputs) {
    const inPath = join(PROOF_DIR, `${name}.inputs.json`);
    writeFileSync(inPath, JSON.stringify(inputs, null, 2) + '\n', 'utf8');
    args.push('--inputs', inPath);
  }

  const outPath = join(PROOF_DIR, `${name}.out.jsonl`);
  args.push('--out', outPath);

  const t0 = performance.now();
  execFileSync(process.execPath, args, { cwd: ROOT, stdio: 'pipe' });
  const elapsedMs = Math.round(performance.now() - t0);
  const raw = readFileSync(outPath, 'utf8');
  const hash = createHash('sha256').update(raw).digest('hex');
  const lines = raw.trim().split('\n').map((l) => JSON.parse(l));
  return { outPath, hash, lines, end: lines.at(-1), elapsedMs };
}

